CREATE OR REPLACE VIEW EMP_DETAILS_VIEW AS
SELECT D.DEPARTMENT_NAME,
       L.CITY,
       R.REGION_NAME
FROM DEPARTMENTS D
JOIN LOCATIONS L
    ON D.LOCATION_ID = L.LOCATION_ID
JOIN REGIONS R
    ON R.REGION_ID = 1
WHERE L.COUNTRY_ID = 'HU';


